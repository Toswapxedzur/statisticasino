// POST /data/export-csv
//
// Body: { handKeys: string[] }
// Response: application/zip — bundle containing
//             casino-export-<stamp>/hands.csv
//             casino-export-<stamp>/actions.csv
//             casino-export-<stamp>/players.csv
//
// Symmetric with /data/export-dump (which returns the .casinodump
// shape): same handKeys[] body, public read (no auth gate). Aimed at
// analytical workflows — pandas / DuckDB / Excel — where the JSON of
// /data/export-dump is awkward to flatten.
//
// Schema spec lives in $lib/server/export-csv.js (buildCsvBundle).
// Card-visibility rule: hole_cards = whatever was visible in the
// captured frames (hero + showdown reveals); board_cards = only the
// community cards that were actually dealt (empty for preflop folds,
// 6 chars for flop folds, 10 chars for showdowns).

import { error } from "@sveltejs/kit";
import { Buffer } from "node:buffer";
import { ZipArchive } from "archiver";
import { loadHandsForExport } from "$lib/server/tables.js";
import { buildCsvBundle } from "$lib/server/export-csv.js";
import { ownerOnly } from "$lib/server/owner-only.js";

// Plain-text doc bundled into every export. Shipped alongside the
// three CSVs so an analyst opening the zip first sees the schema +
// caveats without having to round-trip back to the website. Update
// this in lockstep with any column / semantics change in
// $lib/server/export-csv.js.
const README_TEXT =
`casino-export — CSV bundle
==========================

Generated by /data/export-csv on https://www.sinostatistica.net.
Three CSVs, each row keyed on \`hand_key\` (the join column across all
three tables).

Files
-----
  hands.csv     One row per hand. Hand-level summary.
  actions.csv   One row per authoritative gameplay action, in play order.
  players.csv   One row per (hand, seat) — each player's involvement.

Joining
-------
  hands.hand_key  =  actions.hand_key  =  players.hand_key

Encoding
--------
  * UTF-8, RFC 4180-style CSV (commas, double-quote escaped fields,
    LF line endings).
  * Empty cells mean "no value" for that column. They are distinct
    from explicit zeroes.
  * Timestamps (\`*_ts\`) are integer milliseconds since the Unix epoch
    (UTC). Convert with e.g. \`pd.to_datetime(df.first_ts, unit='ms')\`.

Card representation
-------------------
Cards are two-character codes: rank in {2,3,4,5,6,7,8,9,T,J,Q,K,A}
followed by suit in {c,d,h,s}. Examples: "Ah" = ace of hearts,
"Tc" = ten of clubs.

  * \`hole_cards\` carries WHAT WAS VISIBLE in the captured frames:
      - Hero's two cards (when the export was made from a non-Generic
        hand owned by an account whose hole cards were observed).
      - Any opponent who voluntarily showed at showdown.
      - Otherwise "XX" — masked. The seat received cards but the
        casino didn't reveal them to us.

  * \`board_cards\` reflects ONLY what was actually dealt:
      - ""        — preflop fold; community cards never came out.
      - 6 chars   — flop dealt, hand ended on flop.
      - 8 chars   — turn dealt, hand ended on turn.
      - 10 chars  — river dealt (showdown or river fold).
    "Not dealt" (empty) is therefore distinct from "unknown" (X).
    The dataset is otherwise lossy and we want analysts to be able
    to tell the difference.

  * \`hero_hole_cards\` (in hands.csv) is the canonical-row hero's
    pair if known, otherwise empty. For [Generic] hands no hero is
    recorded and the field is empty.


hands.csv columns
-----------------
  hand_key                  Primary key. Format:
                            <table_topic>::<table_id>::<hand_id>.
  hand_id                   Casino-assigned hand id (string).
  table_id                  Phoenix topic id of the table.
  table_name                First-known display name of the table
                            (e.g. "Low Stakes - Duck Pond - 1/2 -
                            NL Holdem"). May be empty for hands
                            captured before the page title settled.
  first_ts                  Earliest captured frame ts (ms).
  last_ts                   Latest captured frame ts (ms).
  dealer_seat               Seat ID of the button.
  num_seats                 Count of ACTIVE players in the hand
                            (empty felt slots are excluded).
  num_actions               Count of authoritative actions
                            (= row count for this hand in
                            actions.csv).
  hero_seat                 Seat ID of the account that captured
                            this hand. Empty for [Generic] rounds.
  hero_hole_cards           4 chars (e.g. "AhKd") if the hero's
                            cards were captured, else empty.
  board_cards               Concatenated community cards in dealing
                            order. See "Card representation" above.
  street_reached            One of: preflop, flop, turn, river,
                            showdown. "showdown" means the casino
                            emitted its \`showdown\` marker (cards
                            were revealed). A river fold lands as
                            "river"; a showdown lands as "showdown".
  start_hand_ts             Timestamp of the \`startHand\` action.
  finish_hand_ts            Timestamp of the \`finishHand\` action.
  player_name               Canonical-row owner. "[Generic]" means
                            the hand was uploaded under the
                            generic bucket (no hero hole cards).
  player_casino_user_id     Casino user_id of the canonical-row
                            owner. Empty for [Generic].


actions.csv columns
-------------------
One row per authoritative gameplay action, in play order. The
authoritative set is:

  startHand, blinds, dealHoleCards, dealCommunityCards,
  check, call, bet, raise, fold, allIn,
  updatePots, betRefund, showdown, show, muck,
  awardPot, finishHand

Non-authoritative chatter (tick, intent echoes, dealerMessage, …)
is filtered out before this CSV is built.

  hand_key       Foreign key to hands.csv / players.csv.
  step           1-based action index within this hand.
  ts             Timestamp (ms).
  action         One of the action types above.
  street         preflop / flop / turn / river / showdown.
                 Reflects the betting round the action belongs to
                 (board-derived pre-showdown; flips to "showdown"
                 once the casino's \`showdown\` marker has fired).
  seat_id        Seat ID for seat-bound actions
                 (check/call/bet/raise/fold/allIn/show/muck/
                 betRefund). Empty for table-wide actions
                 (startHand/blinds/dealCommunityCards/updatePots/
                 awardPot/finishHand).
  chips          Chip amount for the action when applicable
                 (call/bet/raise/allIn/betRefund). Empty otherwise.
  cards          For dealCommunityCards: the cumulative board at
                 that step. For show: the two revealed cards.
                 Otherwise empty.


players.csv columns
-------------------
One row per (hand, seat). Empty felt slots are filtered out — only
seats that participated in the hand are listed.

  hand_key                       Foreign key.
  seat_id                        Physical felt seat number (1-based,
                                 fixed by the casino).
  casino_user_id                 Casino-side user_id occupying the
                                 seat at startHand. May be empty if
                                 the casino didn't surface it.
  position                       Position label relative to the
                                 button, derived from the active-
                                 seat rotation:
                                   2 players: BTN, BB
                                   3 players: BTN, SB, BB
                                   4 players: BTN, SB, BB, CO
                                   5 players: BTN, SB, BB, HJ, CO
                                   6+ players: BTN, SB, BB, UTG,
                                              UTG+1, …, HJ, CO
  starting_stack                 Stack reported at startHand.
  ending_stack                   Stack reported at finishHand.
  hole_cards                     4 chars or "XX" — see "Card
                                 representation" above.
  voluntarily_put_money_in_pot   1 if the seat made a bet, call,
                                 raise or allIn at any point;
                                 0 otherwise. Posting blinds does
                                 NOT count (standard poker-tracker
                                 VPIP semantics).
  won_amount                     Sum of all chips received in
                                 awardPot rows for this seat across
                                 the hand. 0 if the seat won
                                 nothing.


Caveats
-------
  * Capture is best-effort. If the extension started mid-hand or
    the user closed the tab early, frames may be missing — fields
    derived from them (board_cards, ending_stack, hole_cards reveals)
    will be empty or "XX".
  * Some hands are imported as [Generic] when no hero hole cards
    were observed. For those, hero_seat / hero_hole_cards are
    empty and player_name is "[Generic]".
  * "showdown" street_reached with empty board_cards means the
    casino fired its showdown marker but we missed the
    dealCommunityCards frames. Treat the hand as showdown but
    don't trust the board.
  * Two seats with \`casino_user_id\` empty in the same hand are
    distinct players occupying different physical seats — use
    (hand_key, seat_id) as the primary key on players.csv, not
    (hand_key, casino_user_id).
`;

export async function POST({ request, locals }) {
  ownerOnly(locals);
  let body;
  try { body = await request.json(); }
  catch { throw error(400, "Body must be JSON"); }

  const handKeys = Array.isArray(body && body.handKeys)
    ? body.handKeys.map(String).filter(Boolean)
    : [];
  if (handKeys.length === 0) throw error(400, "handKeys[] required");

  const rows = await loadHandsForExport(handKeys);
  if (rows.length === 0) throw error(404, "No matching hands found");

  const bundle = buildCsvBundle(rows);

  // Bundle into a zip in memory. The biggest of the three CSVs is
  // bounded by hand_count * actions_per_hand * row_width — for the
  // 1254-hand case the user is targeting that's ~3 MB before deflate.
  // Buffering is fine; no need to pipe-stream this.
  const stamp = new Date().toISOString().replace(/[:.]/g, "-");
  const dirInsideZip = `casino-export-${stamp}`;

  const zipBuf = await new Promise((accept, reject) => {
    const archive = new ZipArchive({ zlib: { level: 9 } });
    const chunks = [];
    archive.on("data", (c) => chunks.push(c));
    archive.on("end", () => accept(Buffer.concat(chunks)));
    archive.on("error", reject);
    archive.append(README_TEXT,    { name: `${dirInsideZip}/README.txt` });
    archive.append(bundle.hands,   { name: `${dirInsideZip}/hands.csv` });
    archive.append(bundle.actions, { name: `${dirInsideZip}/actions.csv` });
    archive.append(bundle.players, { name: `${dirInsideZip}/players.csv` });
    archive.finalize();
  });

  const filename = `${dirInsideZip}.zip`;
  return new Response(zipBuf, {
    status: 200,
    headers: {
      "Content-Type": "application/zip",
      "Content-Length": String(zipBuf.length),
      "Content-Disposition": `attachment; filename="${filename}"`
    }
  });
}
